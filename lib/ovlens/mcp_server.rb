module Ovlens
  # A read-only MCP server over the generated documentation. It contains no AI
  # and needs no API key; an MCP client starts it and talks to it over stdio.
  module McpServer
    INSTRUCTIONS = 'Documentation for the Puppet code deployed in OpenVox environments, generated by openvox-strings. ' \
                   'Use search_code to find classes, defined types, functions and other entities, then get_docs for the ' \
                   'details; get_docs takes several names at once. compare_environments shows what differs between two ' \
                   'environments, such as before promoting one to the other. ' \
                   "Only the modules on each environment's module path are covered. Puppet's built-in types and " \
                   'functions (file, package, service, exec, user, cron and so on) are not listed here, which does ' \
                   'not mean they are unavailable.'

    HIERA_INSTRUCTIONS = ' Hiera data is indexed too: find_hiera_key shows where a key is set and which class parameter it ' \
                         'feeds, hiera_for_class shows how each parameter of a class gets its value, and check_hiera ' \
                         'finds keys for parameters that do not exist. Values are masked: encrypted ones show as ' \
                         "#{HieraIndex::ENCRYPTED}, and secrets by name as #{HieraIndex::MASKED}.".freeze

    # The Hiera tools are offered only when some environment's Hiera data has
    # been indexed, which is opt-in.
    def self.build(docs_dir)
      docs = Docs.new(docs_dir)
      hiera = begin
        docs.hiera_environments.any?
      rescue Error
        false
      end
      tools = [ListModules, SearchCode, GetDocs, CompareEnvironments]
      tools += [FindHieraKey, HieraForClass, CheckHiera] if hiera
      MCP::Server.new(
        name: 'ovlens',
        version: VERSION,
        instructions: hiera ? INSTRUCTIONS + HIERA_INSTRUCTIONS : INSTRUCTIONS,
        tools: tools,
        server_context: { docs: docs },
      )
    end

    def self.run(docs_dir)
      MCP::Server::Transports::StdioTransport.new(build(docs_dir)).open
    end

    # Shared schema fragments and reply helpers. Each tool reads the Docs
    # instance from the server context.
    class Tool < MCP::Tool
      ENVIRONMENT = { type: 'string', description: 'Environment name. Defaults to production.' }.freeze
      READ_ONLY = { read_only_hint: true, destructive_hint: false, idempotent_hint: true, open_world_hint: false }.freeze

      class << self
        def reply(data)
          MCP::Tool::Response.new([{ type: 'text', text: JSON.generate(data) }])
        end

        def failure(message)
          MCP::Tool::Response.new([{ type: 'text', text: message }], error: true)
        end
      end
    end

    # Lists the modules in an environment.
    class ListModules < Tool
      tool_name 'list_modules'
      description <<~TEXT
        List the modules deployed in an OpenVox environment, with each module's version and how many documented
        entities it has. Also reports when the documentation was generated and which environments are available.
      TEXT
      input_schema(properties: { environment: ENVIRONMENT })
      annotations(**READ_ONLY)

      def self.call(server_context:, **args)
        docs = server_context[:docs]
        name = docs.resolve(args[:environment])
        index = docs.index(name)
        reply(
          environment: name,
          generated_at: index['generated_at'],
          environments: docs.environments,
          modules: index['modules'].map { |m| m.slice('name', 'version', 'entities', 'error') },
        )
      rescue Error => e
        failure(e.message)
      end
    end

    # Finds entities by name, summary or documentation text.
    class SearchCode < Tool
      DEFAULT_LIMIT = 50
      MAX_LIMIT = 200

      tool_name 'search_code'
      description <<~TEXT
        Search the Puppet code deployed in an OpenVox environment for classes, defined types, functions, data types,
        resource types, providers, tasks and plans. Matches the words in `text` against each entity's name, summary and
        full documentation (parameter names and descriptions included) and returns name, type, module and summary, best
        match first. `match` is "all" when every word matched and "any" when the search fell back to entities matching
        only some of the words. Leave `text` out to list everything of a type or in a module. Follow up with get_docs
        for parameters, defaults and examples. Entities marked `@api private` are hidden unless include_private is true.
        Only modules on the environment's module path are searched: Puppet's built-in types and functions (file,
        package, service, cron and so on) are not listed, and finding none here does not mean they are unavailable.
      TEXT
      input_schema(
        properties: {
          text: { type: 'string', description: 'Words to look for, for example "reverse proxy" or "nginx::resource".' },
          type: { type: 'string', enum: Docs::TYPES, description: 'Only this kind of entity.' },
          module: { type: 'string', description: 'Only this module, for example "nginx".' },
          environment: ENVIRONMENT,
          include_private: { type: 'boolean', description: 'Include entities marked private. Default false.' },
          limit: { type: 'integer', minimum: 1, maximum: MAX_LIMIT, description: "Maximum results (default #{DEFAULT_LIMIT})." },
        },
      )
      annotations(**READ_ONLY)

      def self.call(server_context:, **args)
        docs = server_context[:docs]
        name = docs.resolve(args[:environment])
        matches, mode = docs.search(name, args[:text], type: args[:type], module_name: args[:module])
        visible = args[:include_private] ? matches : matches.reject { |e| e['private'] }
        shown = visible.first((args[:limit] || DEFAULT_LIMIT).to_i.clamp(1, MAX_LIMIT))
        reply(
          environment: name,
          match: mode,
          matches: visible.size,
          returned: shown.size,
          private_hidden: matches.size - visible.size,
          results: shown,
        )
      rescue Error => e
        failure(e.message)
      end
    end

    # Returns the documentation for one or more entities.
    class GetDocs < Tool
      # More entities than this sharing one name is a question, not an answer.
      MAX_FULL = 5
      MAX_NAMES = 20
      # What one reply may hold. MCP clients cut off or set aside tool results
      # much larger than this.
      BUDGET = 40_000
      SHORTENED = 'Some documentation was shortened to fit (see `detail`). Call get_docs again with `parameters` ' \
                  'to read particular parameters or properties in full.'

      tool_name 'get_docs'
      description <<~TEXT
        Get the documentation for one or more entities in an OpenVox environment by exact name, for example
        "nginx::resource::server" or "stdlib::ensure_packages": description, parameters with types and defaults,
        examples, return type, and the file and line each is defined at. Pass several names in `names` to read them
        in one call. Use search_code first if you do not know the exact names. Pass type or module when a name is
        ambiguous (several providers are called "ruby", for instance). Set include_source to also get the source code.
        A very large entity comes back shortened, and `detail` says how: "condensed" keeps every parameter with the
        first sentence of its description, "outline" keeps names, types and defaults only. Call again with
        `parameters` to read particular parameters or properties of one entity in full.
      TEXT
      input_schema(
        properties: {
          names: {
            type: 'array', items: { type: 'string' }, maxItems: MAX_NAMES,
            description: 'Exact entity names, one or more.'
          },
          name: { type: 'string', description: 'One exact entity name. Same as a single entry in `names`.' },
          type: { type: 'string', enum: Docs::TYPES, description: 'Kind of entity, to disambiguate.' },
          module: { type: 'string', description: 'Module name, to disambiguate.' },
          environment: ENVIRONMENT,
          parameters: {
            type: 'array', items: { type: 'string' },
            description: 'Return only these parameters or properties, in full.'
          },
          include_source: { type: 'boolean', description: 'Include the source code. Default false.' },
        },
      )
      annotations(**READ_ONLY)

      class << self
        def call(server_context:, **args)
          docs = server_context[:docs]
          names = ([args[:name]] + Array(args[:names])).compact.map(&:to_s).uniq.first(MAX_NAMES)
          return failure('Give at least one entity name in `names`.') if names.empty?

          env = docs.resolve(args[:environment])
          entries = docs.entries(env, type: args[:type], module_name: args[:module])
          found, missing, ambiguous = sort_out(docs, entries, names)
          return nothing_found(env, missing) if found.empty? && ambiguous.empty?

          entities = found.map { |entry| docs.entity(env, entry, include_source: args[:include_source]) }
          reply(assemble(env, entities, args[:parameters]).merge(extras(missing, ambiguous)))
        rescue Error => e
          failure(e.message)
        end

        private

        # Splits the names into index entries to return, names that match
        # nothing, and names that match too many entities to return them all.
        def sort_out(docs, entries, names)
          found = []
          missing = []
          ambiguous = []
          names.each do |name|
            matches = entries.select { |e| e['name'].casecmp?(name) }
            if matches.empty?
              missing << { name: name, did_you_mean: docs.suggestions(entries, name) }
            elsif matches.size > MAX_FULL
              ambiguous << { name: name, hint: 'Pass type or module to pick one.', candidates: matches }
            else
              found.concat(matches)
            end
          end
          [found, missing, ambiguous]
        end

        def nothing_found(env, missing)
          if missing.size == 1
            only = missing.first
            return failure(JSON.generate(error: "Nothing named #{only[:name].inspect} in #{env}.", did_you_mean: only[:did_you_mean]))
          end
          failure(JSON.generate(error: "None of these names exist in #{env}.", not_found: missing))
        end

        # Fits the entities into the reply's budget and names the ones that did
        # not fit at all. Room for every entity's shortest form is set aside
        # first, so a large one is shortened before another is left out; the
        # smallest are placed first, and what they leave unused goes to the rest.
        def assemble(env, entities, parameters)
          sized = entities.map do |entity|
            full = Excerpt.size(entity['docs'])
            [entity, full, [full, Excerpt.size(Excerpt.outline(entity['docs']))].min]
          end
          left = BUDGET
          reserved = sized.sum { |_, _, least| least }
          placed = {}
          omitted = []
          sized.sort_by { |_, full, _| full }.each do |entity, _, least|
            reserved -= least
            result = parameters ? picked(entity, parameters) : fitted(entity, [left - reserved, 0].max)
            size = Excerpt.size(result)
            if size > left
              omitted << entity['docs']['name']
            else
              left -= size
              placed[entity] = result
            end
          end

          results = entities.filter_map { |entity| placed[entity] }
          shortened = results.any? { |result| result.key?('detail') }
          reply = { environment: env, results: results }
          reply[:omitted] = omitted.uniq unless omitted.empty?
          reply[:hint] = hint(shortened, omitted) if shortened || !omitted.empty?
          reply
        end

        def fitted(entity, room)
          docs, detail = Excerpt.fit(entity['docs'], room)
          result = entity.merge('docs' => docs)
          result['detail'] = detail unless detail == 'full'
          result
        end

        def picked(entity, parameters)
          docs, unknown = Excerpt.only(entity['docs'], parameters)
          result = entity.merge('docs' => docs)
          result['unknown_parameters'] = unknown unless unknown.empty?
          result
        end

        def hint(shortened, omitted)
          [
            (SHORTENED if shortened),
            ('The entities under `omitted` did not fit in this reply; ask for them in another call.' unless omitted.empty?)
          ].compact.join(' ')
        end

        def extras(missing, ambiguous)
          extra = {}
          extra[:not_found] = missing unless missing.empty?
          extra[:ambiguous] = ambiguous unless ambiguous.empty?
          extra
        end
      end
    end

    # Compares two environments' modules and entities.
    class CompareEnvironments < Tool
      BUDGET = 40_000
      # Tried in order until the reply fits the budget.
      SHORTER = [{ entities: 20 }, { entities: 0 }, { entities: 0, modules: 100 }, { entities: 0, modules: 25 }].freeze

      tool_name 'compare_environments'
      description <<~TEXT
        Compare two documented OpenVox environments, for example before promoting one to the other or to see how far
        two have drifted: modules added or removed, modules whose version changed, modules whose code changed within
        the same version (and whether their documentation changed with it), and the classes, defined types,
        functions, types, tasks and plans added or removed. Unchanged modules are only counted. This compares what
        exists, not parameters: for those, call get_docs on both environments. Pass `module` to compare one module.
      TEXT
      input_schema(
        properties: {
          from: { type: 'string', description: 'The environment to compare from, for example "production".' },
          to: { type: 'string', description: 'The environment to compare to, for example "staging".' },
          module: { type: 'string', description: 'Compare only this module.' },
        },
        required: %w[from to],
      )
      annotations(**READ_ONLY)

      def self.call(from:, to:, server_context:, **args)
        docs = server_context[:docs]
        comparison = Comparison.new(docs, docs.resolve(from), docs.resolve(to), module_name: args[:module])
        reply(fit(comparison))
      rescue Error => e
        failure(e.message)
      end

      def self.fit(comparison)
        report = comparison.to_h
        return report if Excerpt.size(report) <= BUDGET

        SHORTER.each do |limits|
          report = comparison.shortened(**limits)
          break if Excerpt.size(report) <= BUDGET
        end
        report.merge('hint' => 'Some lists were shortened to fit (see the *_omitted counts). Pass `module` to see ' \
                               'one module in full.')
      end
    end

    # Shared by the Hiera tools: runs a query, shortening values until the
    # reply fits.
    class HieraTool < Tool
      BUDGET = 40_000
      ENVIRONMENT_HELP = 'Environment name. Defaults to production.'

      def self.answer(docs, environment)
        environment = docs.resolve(environment)
        result = nil
        [HieraQuery::VALUE_LIMIT, 100, 0].each do |limit|
          result = yield HieraQuery.new(docs, environment, value_limit: limit)
          return reply(result) if Excerpt.size(result) <= BUDGET
        end
        reply(result.merge('hint' => 'Values were shortened to fit; ask about fewer keys or one class at a time.'))
      rescue Error => e
        failure(e.message)
      end
    end

    # Where a Hiera key is set.
    class FindHieraKey < HieraTool
      tool_name 'find_hiera_key'
      description <<~TEXT
        Find where a Hiera key is set in an OpenVox environment: every hierarchy level and file, in the environment's
        data and in module data, with the value, and the class parameter the key feeds through automatic parameter
        lookup, with its type and default, and the files whose code looks it up by name. Give an exact key such as
        "ntp::servers", or part of one to list the keys containing it. Values are masked: encrypted ones show as
        <encrypted>, and secrets by name as <masked>. This lists every place a key is set; which one a given node gets
        depends on its facts.
      TEXT
      input_schema(
        properties: {
          key: { type: 'string', description: 'The key, or part of one.' },
          environment: { type: 'string', description: ENVIRONMENT_HELP },
        },
        required: ['key'],
      )
      annotations(**READ_ONLY)

      def self.call(key:, server_context:, **args)
        answer(server_context[:docs], args[:environment]) { |query| query.find(key) }
      end
    end

    # How each parameter of a class gets its value.
    class HieraForClass < HieraTool
      tool_name 'hiera_for_class'
      description <<~TEXT
        Show how each parameter of a class in an OpenVox environment gets its value: its type, its default in the
        code, module data that overrides that default, and the environment's Hiera data that sets it, by hierarchy
        level and file. Parameters with no default and no data are marked: the class cannot be included without a
        value for them. Also lists keys under the class's name for parameters it does not have.
      TEXT
      input_schema(
        properties: {
          class: { type: 'string', description: 'Class name, for example "ntp" or "profile::base".' },
          environment: { type: 'string', description: ENVIRONMENT_HELP },
        },
        required: ['class'],
      )
      annotations(**READ_ONLY)

      def self.call(server_context:, **args)
        answer(server_context[:docs], args[:environment]) { |query| query.for_class(args[:class]) }
      end
    end

    # Problems in an environment's Hiera data.
    class CheckHiera < HieraTool
      tool_name 'check_hiera'
      description <<~TEXT
        Check an environment's own Hiera data: keys for class parameters that do not exist (a typo, or data left
        behind after a parameter was removed; OpenVox ignores these silently), hierarchy levels that could not be
        indexed, and data files that could not be read. Keys the code reads with lookup() are not reported.
      TEXT
      input_schema(properties: { environment: { type: 'string', description: ENVIRONMENT_HELP } })
      annotations(**READ_ONLY)

      def self.call(server_context:, **args)
        answer(server_context[:docs], args[:environment], &:check)
      end
    end
  end
end
